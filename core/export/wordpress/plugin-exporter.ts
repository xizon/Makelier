import fs from 'node:fs';
import path from 'node:path';

import {
    PLUGIN_NAME,
    PLUGIN_TITLE,
    PLUGIN_TESTED_UP_TO,
    EXTERNAL_GLOBALS,
    EXTERNAL_LIB,
} from '../../utils/const.ts';

import type {
    ExternalLibraryList
} from '../../utils/types.ts';


/**
 * NOTE: ONLY for organizing and copying the final files.
 */


/**
 * Discover external libraries from package.json.
 *
 * Only dependencies supported by both EXTERNAL_GLOBALS
 * and EXTERNAL_LIB will be included.
 */
function getExternalLibraries(siteRoot: string): ExternalLibraryList[] {
    const packagePath = path.join(siteRoot, 'package.json');

    if (!fs.existsSync(packagePath)) {
        return [];
    }

    const packageJson = JSON.parse(
        fs.readFileSync(packagePath, 'utf8'),
    );

    const dependencies = packageJson.dependencies ?? {};

    return Object.keys(dependencies)
        .filter(name => EXTERNAL_GLOBALS[name] && EXTERNAL_LIB[name])
        .map((name): ExternalLibraryList => ({
            name,
            fileName: EXTERNAL_LIB[name].fileName,
            ver: EXTERNAL_LIB[name].ver,
        }));
}

/**
 * Copy external JavaScript libraries into the plugin.
 */
function copyExternalScripts(
    siteRoot: string,
    pluginDir: string,
): void {
    const libraries = getExternalLibraries(siteRoot);

    if (libraries.length === 0) {
        return;
    }

    // Makelier bundled external libraries.
    const sourceDir = path.resolve(
        process.cwd(),
        'tools/externals-lib/js',
    );

    const outputDir = path.join(
        pluginDir,
        'assets',
        'js',
    );

    fs.mkdirSync(outputDir, { recursive: true });

    for (const { name, fileName } of libraries) {
        const sourcePath = path.join(sourceDir, fileName);
        const outputPath = path.join(outputDir, fileName);

        if (!fs.existsSync(sourcePath)) {
            throw new Error(
                `[Makelier] External library "${name}" not found: ${sourcePath}`,
            );
        }

        fs.copyFileSync(sourcePath, outputPath);
    }
}

/**
 * Generate external frontend dependency scripts.
 */
function generateExternalScriptsPhp(siteRoot: string): string {
    const libraries = getExternalLibraries(siteRoot);

    if (libraries.length === 0) {
        return '';
    }

    const dependencyInfo = libraries
        .map(({ name, fileName, ver }) => ` * - ${name}: ${ver} (${fileName})`)
        .join('\n');

    const registerScripts = libraries.map(({ name, fileName, ver }) => {
        const handle = `makelier-${name.replace(/[^a-zA-Z0-9_-]/g, '-')}`;

        return `    wp_register_script(
        '${handle}',
        plugin_dir_url(__FILE__) . 'assets/js/${fileName}',
        array(),
        '${ver}',
        true
    );`;
    }).join('\n\n');

    const enqueueScripts = libraries.map(({ name }) => {
        const handle = `makelier-${name.replace(/[^a-zA-Z0-9_-]/g, '-')}`;

        return `    wp_enqueue_script('${handle}');`;
    }).join('\n');

    return `
/**
 * External Dependencies
 *
 * Automatically generated from package.json and EXTERNAL_LIB.
 *
 * Dependencies:
${dependencyInfo}
 */

/**
 * Register external frontend dependencies.
 */
function makelier_blocks_register_externals(): void {
${registerScripts}
}

add_action('init', 'makelier_blocks_register_externals');

/**
 * Enqueue external frontend dependencies.
 */
function makelier_blocks_enqueue_externals(): void {
${enqueueScripts}
}

add_action('wp_enqueue_scripts', 'makelier_blocks_enqueue_externals');
`;
}

/**
 * Generate the main WordPress plugin PHP file.
 */
function generatePluginPhp(siteRoot: string): string {
    return `<?php
/**
 * Plugin Name: ${PLUGIN_TITLE}
 * Description: Gutenberg blocks generated by Makelier.
 * Version: 1.0.0
 * Author: Makelier
 * Text Domain: ${PLUGIN_NAME}
 */

if (!defined('ABSPATH')) {
    exit;
}

${generateExternalScriptsPhp(siteRoot)}

/**
 * Enqueue shared Tailwind CSS.
 */
function makelier_blocks_enqueue_styles(): void {
    $css_path = plugin_dir_path(__FILE__) . 'assets/tailwind.css';

    if (!file_exists($css_path)) {
        return;
    }

    wp_enqueue_style(
        'makelier-tailwind',
        plugin_dir_url(__FILE__) . 'assets/tailwind.css',
        array(),
        filemtime($css_path)
    );
}

add_action('enqueue_block_assets', 'makelier_blocks_enqueue_styles');

/**
 * Register all blocks.
 */
function makelier_blocks_register(): void {
    $blocks_dir = plugin_dir_path(__FILE__) . 'blocks/';

    if (!is_dir($blocks_dir)) {
        return;
    }

    $block_json_files = glob($blocks_dir . '*/block.json');

    if (!$block_json_files) {
        return;
    }

    foreach ($block_json_files as $block_json_file) {
        register_block_type(dirname($block_json_file));
    }
}

add_action('init', 'makelier_blocks_register');
`;
}

/**
 * Generate WordPress editor asset dependencies.
 */
function generateEditorAssetPhp(): string {
    return `<?php
return array(
    'dependencies' => array(
        'wp-blocks',
        'wp-element',
        'wp-block-editor',
        'wp-components',
    ),
    'version' => '1.0.0',
);
`;
}

/**
 * Copy block files into the exported plugin directory.
 */
function copyBlockFiles(
    sourceDir: string,
    outputDir: string,
): number {
    const entries = fs.readdirSync(sourceDir, {
        withFileTypes: true,
    });

    let count = 0;

    for (const entry of entries) {
        if (!entry.isDirectory()) {
            continue;
        }

        const blockSourceDir = path.join(sourceDir, entry.name);
        const blockJsonPath = path.join(blockSourceDir, 'block.json');

        if (!fs.existsSync(blockJsonPath)) {
            continue;
        }

        const blockOutputDir = path.join(outputDir, entry.name);

        fs.mkdirSync(blockOutputDir, { recursive: true });

        const blockFiles = [
            { name: 'block.json', required: true },
            { name: 'config.json', required: false },
            { name: 'edit.js', required: true },
            { name: 'view.js', required: false },
        ];

        for (const file of blockFiles) {
            const sourcePath = path.join(blockSourceDir, file.name);

            if (!fs.existsSync(sourcePath)) {
                if (file.required) {
                    throw new Error(
                        `[Makelier] Missing ${file.name} for block: ${entry.name}`,
                    );
                }

                continue;
            }

            fs.copyFileSync(
                sourcePath,
                path.join(blockOutputDir, file.name),
            );
        }

        // Copy the block-specific stylesheet.
        const styleSourcePath = path.join(
            blockSourceDir,
            'component-pure.css',
        );

        if (fs.existsSync(styleSourcePath)) {
            fs.copyFileSync(
                styleSourcePath,
                path.join(blockOutputDir, 'component-pure.css'),
            );
        }

        // Generate WordPress editor asset dependencies.
        fs.writeFileSync(
            path.join(blockOutputDir, 'edit.asset.php'),
            generateEditorAssetPhp(),
            'utf8',
        );

        count++;
    }

    return count;
}

/**
 * Export the WordPress plugin.
 */
export function exportWordPressPlugin(siteRoot: string): void {
    const sourceDir = path.join(siteRoot, '.makelier', 'wp');
    const outputRoot = path.join(siteRoot, 'dist-wp');
    const pluginDir = path.join(outputRoot, PLUGIN_NAME);
    const blocksDir = path.join(pluginDir, 'blocks');

    if (!fs.existsSync(sourceDir)) {
        throw new Error(
            `[Makelier] WordPress build directory not found: ${sourceDir}`,
        );
    }

    // Remove previous export to prevent stale blocks.
    fs.rmSync(pluginDir, {
        recursive: true,
        force: true,
    });

    fs.mkdirSync(blocksDir, { recursive: true });

    const blockCount = copyBlockFiles(sourceDir, blocksDir);

    // Copy external JavaScript libraries.
    copyExternalScripts(siteRoot, pluginDir);

    // Generate the main plugin PHP file.
    fs.writeFileSync(
        path.join(pluginDir, 'makelier-blocks.php'),
        generatePluginPhp(siteRoot),
        'utf8',
    );

    // Generate plugin readme.
    const README = `=== ${PLUGIN_TITLE} ===
Contributors: __string__
Author URI: __string__
Plugin URL: __string__
Tags: blocks, gutenberg
Requires at least: 6.0
Requires PHP: 7.4
Tested up to: ${PLUGIN_TESTED_UP_TO}
Stable tag: 1.0.0
License: GPLv2 or later
License URI: http://www.gnu.org/licenses/gpl-2.0.html

Gutenberg blocks generated by Makelier.
`;

    fs.writeFileSync(
        path.join(pluginDir, 'readme.txt'),
        README,
        'utf8',
    );

    console.log(
        `[Makelier] Exported ${blockCount} WordPress block(s) to: ${pluginDir}`,
    );
}